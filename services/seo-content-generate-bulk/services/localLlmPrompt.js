const WORD_COUNT_TEXT = 'приблизительно 2000 символов, + - 500 символов';

/**
 * Собирает задание для одной статьи (как taskPrompt в PHP).
 */
function buildTaskPrompt(topic) {
  const title = String(topic || '').trim() || '';
  let task = '\n\nЗАДАНИЕ ДЛЯ ЭТОЙ СТАТЬИ:';
  task += title ? `\nЗаголовок: ${title}` : '\nСгенерируй привлекательный заголовок';
  task += '\nСгенерируй релевантные ключевые слова';
  task += `\nОбъём: ${WORD_COUNT_TEXT}`;
  return task;
}

/**
 * Заменяет комментарии <!-- ИЗОБРАЖЕНИЕ: ... --> на HTML-плейсхолдеры (как processImageComments в PHP).
 */
function processImageComments(content) {
  if (!content || typeof content !== 'string') return content;
  return content.replace(
    /<!-- ИЗОБРАЖЕНИЕ: ([^|]+)\|([^>]+) -->/g,
    (_, description, altPart) => {
      const desc = description.trim();
      const alt = altPart.replace(/^alt="|"$/g, '').trim();
      return `<div class="image-placeholder">
                    <p >
                        📷 <strong>Рекомендуется изображение:</strong><br>
                        <span style="font-size: 14px;">${escapeHtml(desc)}</span><br>
                        <span style="font-size: 12px;">Alt: "${escapeHtml(alt)}"</span>
                    </p>
                </div>`;
    }
  );
}

function escapeHtml(s) {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

module.exports = { BASE_PROMPT, buildTaskPrompt, processImageComments };
